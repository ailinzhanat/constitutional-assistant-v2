def format_redirect_message(redirect_info: dict, lang: str = "ru") -> str:
    """
    Форматирует сообщение о перенаправлении для пользователя.
    """
    if lang == "kz":
        header = ""
        advice = redirect_info.get("advice_kz", "")
        organs_header = "📋 Мына органдарға жүгінуді ұсынамыз:"
    else:
        header = ""
        advice = redirect_info.get("advice_ru", "")
        organs_header = "📋 Рекомендуем обратиться:"
    
    parts = [header, "", advice]
    
    if redirect_info.get("organs"):
        parts.append("")
        parts.append(organs_header)
        for organ in redirect_info["organs"]:
            line = f"  • {organ['name']}"
            if organ.get("link"):
                line += f"\n    🔗 {organ['link']}"
            parts.append(line)
    
    return "\n".join(parts)
